#!/usr/bin/env python3
"""Embed the frozen spaCy development panel for on-device parity replays.

Mobile integration tests cannot read the repository, so this writes the 16
development inputs and their frozen `tokens`/`sentences` annotations (the
exact fields `packages/quds_proofing_spacy/tool/replay_development.dart`
compares) into a Dart source file next to the test, together with the
manifest and per-case SHA-256 they came from. A VM test re-derives the file
from the fixtures, so the embedded copy cannot drift.

    python3 tools/proofing/spacy/mobile_development_cases.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
FIXTURES = ROOT / "tools/proofing/spacy/fixtures/development"
TARGET = ROOT / "packages/quds_office_editor/example/integration_test/spacy_development_cases.g.dart"
MANIFEST_SHA256 = "9a3bb6bae6114adcf579840834ddcb64dea4e0aaa8361718dc7a551d663c8f7c"


def payload() -> dict:
    manifest_bytes = (FIXTURES / "manifest.json").read_bytes()
    if hashlib.sha256(manifest_bytes).hexdigest() != MANIFEST_SHA256:
        raise SystemExit("Frozen development manifest changed.")
    manifest = json.loads(manifest_bytes)
    cases = []
    for item in manifest["cases"]:
        case_id = item["id"]
        entry = next(e for e in item["files"] if e["path"] == f"{case_id}/case.json")
        data = (FIXTURES / case_id / "case.json").read_bytes()
        if hashlib.sha256(data).hexdigest() != entry["sha256"]:
            raise SystemExit(f"Development reference changed: {case_id}")
        reference = json.loads(data)
        cases.append({
            "id": case_id,
            "case_sha256": entry["sha256"],
            "input_sha256": item["input_sha256"],
            "text": reference["case"]["text"],
            "tokens": reference["annotations"]["tokens"],
            "sentences": reference["annotations"]["sentences"],
        })
    return {"manifest_sha256": MANIFEST_SHA256, "cases": cases}


def render() -> str:
    encoded = json.dumps(payload(), ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    # Raw Dart string: the JSON contains no ''' sequence.
    if "'''" in encoded:
        raise SystemExit("unexpected quote run")
    return ("// GENERATED by tools/proofing/spacy/mobile_development_cases.py; do not edit.\n"
            "// Frozen spaCy development panel (16 cases) for on-device parity.\n"
            "// ignore_for_file: lines_longer_than_80_chars\n"
            f"const spacyDevelopmentPanelJson = r'''{encoded}''';\n")


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(TARGET)
